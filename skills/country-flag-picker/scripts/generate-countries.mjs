// Regenerates reference/countries.ts with the full ISO 3166-1 alpha-2 set.
//
//   cd <any scratch dir>
//   npm i i18n-iso-countries libphonenumber-js
//   node <skill>/scripts/generate-countries.mjs > countries.ts
//
// Sources:
//   codes      i18n-iso-countries  (249 officially assigned codes + XK Kosovo, user-assigned)
//   dial codes libphonenumber-js   (ITU country calling codes; "" where none exists)
//   names      Intl.DisplayNames("en"), with a few common-usage names kept as overrides
//
// Re-run when either package publishes a change (new code, renamed country, new calling code).

import { createRequire } from "node:module";
// Resolve packages from the directory you run it in, not from the skill folder.
const require = createRequire(process.cwd() + "/");
const iso = require("i18n-iso-countries");
const { getCountryCallingCode } = require("libphonenumber-js");

// Common-usage names that replace Intl's English name (e.g. "Ivory Coast" over "Côte d’Ivoire").
const NAME_OVERRIDES = {
  AG: "Antigua and Barbuda", BA: "Bosnia and Herzegovina", CG: "Congo", CD: "Congo (DRC)",
  CZ: "Czech Republic", HK: "Hong Kong", CI: "Ivory Coast", MO: "Macau", MM: "Myanmar",
  PS: "Palestine", KN: "Saint Kitts and Nevis", LC: "Saint Lucia",
  VC: "Saint Vincent and the Grenadines", ST: "Sao Tome and Principe",
  TT: "Trinidad and Tobago", TR: "Turkey",
};

const display = new Intl.DisplayNames(["en"], { type: "region" });
const tidy = (n) => n.replace(/ & /g, " and ").replace(/^St\. /, "Saint ");

const rows = Object.keys(iso.getAlpha2Codes()).map((code) => {
  let dialCode = "";
  try { dialCode = "+" + getCountryCallingCode(code); } catch { /* no calling code */ }
  return { code, name: NAME_OVERRIDES[code] ?? tidy(display.of(code)), dialCode };
});
rows.sort((a, b) => a.name.localeCompare(b.name, "en"));

const q = (s) => JSON.stringify(s);
const out = [
  "// GENERATED by country-flag-picker/scripts/generate-countries.mjs — do not hand-edit.",
  `// Full ISO 3166-1 alpha-2 set (${rows.length} entries incl. XK Kosovo, which is user-assigned, not ISO).`,
  "// dialCode is the ITU country calling code only (NANP countries are all \"+1\"); \"\" = no calling code.",
  "",
  "export interface Country {",
  "  code: string;",
  "  name: string;",
  "  dialCode: string;",
  "}",
  "",
  "export const countries: Country[] = [",
  ...rows.map((r) => `  { code: ${q(r.code)}, name: ${q(r.name)}, dialCode: ${q(r.dialCode)} },`),
  "];",
  "",
  "/** Countries that can be dialled — use this list for phone-number pickers. */",
  "export const phoneCountries: Country[] = countries.filter((c) => c.dialCode !== \"\");",
  "",
  "export function getCountryByCode(code: string): Country | undefined {",
  "  return countries.find((c) => c.code === code);",
  "}",
  "",
  "/** Not unique: +1 is shared by the US, Canada and the Caribbean NANP members, +7 by RU/KZ, etc. */",
  "export function getCountriesByDialCode(dialCode: string): Country[] {",
  "  return countries.filter((c) => c.dialCode === dialCode);",
  "}",
  "",
];
process.stdout.write(out.join("\n"));
